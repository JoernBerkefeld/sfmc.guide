/**
 * mcdev Pipeline Builder — validations builder (pure, DOM-free).
 *
 * Exposes `buildValidations(wizardState)` which returns the full source text of a
 * `.mcdev-validations.js` file. Every config-derived value is interpolated through
 * `JSON.stringify` so a quote/backslash/newline in a BU name can never break the emitted
 * file's syntax. The rule bodies are original rewrites — no client brand names or MIDs.
 *
 * Authored as a classic browser script (IIFE + browser global) with a UMD-style footer so
 * the Node test can `require()` it. NOT an ES module.
 *
 * @typedef {import('./mcdev-pipeline-config-builder.js').WizardState} WizardState
 *
 * @typedef {object} ValidationsState
 * @property {{[bu: string]: string}} buSuffixMap bare-BU-name -> suffix
 * @property {string} separator suffix separator
 * @property {string} devBU bare name of the DEV (env index 0) source BU
 * @property {string[]} selectedRules ids of the checkbox rules the user picked
 * @property {{[bu: string]: boolean}} prodMap bare-BU-name -> is-production
 * @property {number[]} mids business-unit MIDs to scan for (noMidDependentCode)
 * @property {{[bu: string]: string[]}} prefixBlacklist bare-BU-name -> forbidden prefixes (filterPrefixByBu)
 * @property {object} retention sendableDeRetention policy values
 */

/**
 * @param {Window|globalThis} global host object to attach the browser global to
 */

(function (global) {
    'use strict';

    /**
     * JSON literal helper — stable, double-quoted, safe for both keys and string values.
     *
     * @param {unknown} value any JSON-serialisable value
     * @returns {string} JSON text
     */
    function jsonLit(value) {
        return JSON.stringify(value);
    }

    /**
     * Header block: JSDoc typedefs + the module-scope maps that genuinely depend on the BU list.
     *
     * @param {ValidationsState} state collected answers
     * @param {boolean} needProductionMap whether a prod-scoped rule is selected
     * @returns {string} header source
     */
    function header(state, needProductionMap) {
        let out = "'use strict';\n\n";
        out +=
            '/**\n' +
            ' * Generated by the mcdev Pipeline Builder (sfmc.guide/tools/mcdev-pipeline-builder/).\n' +
            ' * Merge these rules into your existing .mcdev-validations.js by hand.\n' +
            ' *\n' +
            ' * @typedef {Object.<string, any>} MetadataTypeItem generic metadata item\n' +
            ' *\n' +
            ' * @typedef {object} CodeExtract\n' +
            ' * @property {string[]} subFolder subfolder path split into elements\n' +
            ' * @property {string} fileName file name without extension\n' +
            ' * @property {string} fileExt file extension\n' +
            ' * @property {string} content file content\n' +
            ' *\n' +
            ' * @callback validationRuleFix\n' +
            ' * @returns {boolean|null} true = passed; false = failed & fixed; null = failed & item removed\n' +
            ' *\n' +
            ' * @callback validationRuleTest\n' +
            ' * @returns {boolean} true = passed; false = failed\n' +
            ' *\n' +
            ' * @typedef {object} validationRule\n' +
            ' * @property {string} failedMsg message shown when the test fails\n' +
            ' * @property {validationRuleTest} passed test to run\n' +
            ' * @property {validationRuleFix} [fix] optional auto-fix\n' +
            ' *\n' +
            ' * @typedef {Object.<string, validationRule>} validationRuleList key = rule name\n' +
            ' */\n\n';

        out += 'const buSuffixMap = ' + prettyMap(state.buSuffixMap) + ';\n';
        if (needProductionMap) {
            out += 'const prodBUorNotMap = ' + prettyMap(state.prodMap) + ';\n';
        }
        return out + '\n';
    }

    /**
     * Render a flat string/boolean map with 4-space indentation and JSON-safe keys/values.
     *
     * @param {{[key: string]: string|boolean}} map source map
     * @returns {string} pretty-printed object literal
     */
    function prettyMap(map) {
        const keys = Object.keys(map || {});
        if (keys.length === 0) {
            return '{}';
        }
        const lines = keys.map((k) => ' '.repeat(4) + jsonLit(k) + ': ' + jsonLit(map[k]) + ',');
        return '{\n' + lines.join('\n') + '\n}';
    }

    /**
     * The `validation(...)` function wrapper and its per-item locals.
     *
     * @param {boolean} needProductionMap whether prod scoping is used
     * @returns {string} opening source of the exported function
     */
    function functionOpen(needProductionMap) {
        let out =
            '/**\n' +
            ' * @param {any} definition type definition\n' +
            ' * @param {MetadataTypeItem} item metadata item\n' +
            ' * @param {string} targetDir deploy folder (deploy/cred/bu)\n' +
            ' * @param {CodeExtract[]} codeExtractItemArr extracted code snippets\n' +
            ' * @param {any} Util mcdev utility helpers\n' +
            ' * @returns {validationRuleList} the rules to run\n' +
            ' */\n';
        out += 'export function validation(definition, item, targetDir, codeExtractItemArr, Util) {\n';
        out +=
            '    // derive the current BU name from the deploy folder path\n' +
            "    const bu = targetDir.includes('/') ? targetDir.split('/').pop() : targetDir.split('\\\\').pop();\n";
        out += '    const suffix = buSuffixMap[bu];\n';
        if (needProductionMap) {
            out += '    const isProd = prodBUorNotMap[bu];\n';
        }
        out +=
            '    if (suffix === undefined) {\n' +
            "        Util.logger.error(`BU '${bu}' has no suffix defined in buSuffixMap in .mcdev-validations.js`);\n" +
            '    }\n';
        out += '    return {\n';
        return out;
    }

    /**
     * Registry of self-contained rule emitters. Each returns the rule's object-literal body
     * (already indented to sit inside the returned map).
     */
    const RULES = {
        keySuffix: () =>
            block('keySuffix', {
                failed: "failedMsg: 'Key suffix expected but not found: ' + suffix,",
                fix: skipFix(),
                passed: lines(
                    "const relevantTypes = ['asset', 'dataExtension'];",
                    'if (!relevantTypes.includes(definition.type)) {',
                    '    return true;',
                    '}',
                    'if (',
                    "    (definition.type === 'dataExtension' &&",
                    "        item.r__folder_ContentType !== 'shared_dataextension') ||",
                    "    suffix === ''",
                    ') {',
                    '    // only shared DEs need a suffix; the parent BU (empty suffix) is exempt',
                    '    return true;',
                    '}',
                    "const key = item[definition.keyField] + '';",
                    'return key ? key.endsWith(suffix) : true;'
                ),
            }),

        noGuidKeys: () =>
            block('noGuidKeys', {
                failed: "failedMsg: 'Key is still in GUID format. Please rename it to a readable key.',",
                passed: lines(
                    'const key = item[definition.keyField];',
                    'if (!key) {',
                    '    return true;',
                    '}',
                    'const guidPattern =',
                    '    /^[0-9a-z]{8}-[0-9a-z]{4}-[0-9a-z]{4}-[0-9a-z]{4}-[0-9a-z]{12}$/i;',
                    'return !guidPattern.test(String(key));'
                ),
            }),

        properJourneyDeNameAndKey: () =>
            block('properJourneyDeNameAndKey', {
                failed: "failedMsg: 'Journey data extension still carries the default New Journey name or key. Please rename it.',",
                passed: lines(
                    "if (definition.type !== 'dataExtension') {",
                    '    return true;',
                    '}',
                    "const defaultName = 'New Journey - ';",
                    'return !(',
                    '    String(item.Name).startsWith(defaultName) ||',
                    '    String(item.CustomerKey).startsWith(defaultName)',
                    ');'
                ),
            }),

        filterText: (state) =>
            blockRaw(
                'filterText',
                lines(
                    '/** @type {string[]} lower-case fragments that must not appear */',
                    'blacklistedStrings: ' + jsonLit(FILTER_TEXT_BLACKLIST) + ',',
                    'whitelistedStrings: ' + jsonLit(FILTER_TEXT_WHITELIST) + ',',
                    'get failedMsg() {',
                    "    return `Not allowed to have one of ${this.blacklistedStrings.join(', ')} in name, key or folder path.`;",
                    '},',
                    '/** @type {validationRuleFix} */',
                    'fix: function () {',
                    '    return this.passed() || null;',
                    '},',
                    '/** @type {validationRuleTest} */',
                    'passed: function () {',
                    '    // the dev source BU is exempt so testing is not blocked',
                    '    if (bu === ' + jsonLit(state.devBU) + ') {',
                    '        return true;',
                    '    }',
                    "    const haystack = [item[definition.keyField], item[definition.nameField], item.r__folder_Path]",
                    "        .map((v) => ('' + v).toLowerCase());",
                    '    for (const bad of this.blacklistedStrings) {',
                    '        const hit = haystack.some((v) => v.includes(bad));',
                    '        const allowed = this.whitelistedStrings.some((ok) =>',
                    '            haystack.some((v) => v.includes(ok))',
                    '        );',
                    '        if (hit && !allowed) {',
                    '            return false;',
                    '        }',
                    '    }',
                    '    return true;',
                    '}'
                )
            ),

        noSharedAssets: () =>
            block('noSharedAssets', {
                failed: "failedMsg: 'Shared assets are not allowed here. Clone the asset across BUs with mcdev instead.',",
                fix: skipFix(),
                passed: lines(
                    "if (definition.type !== 'asset') {",
                    '    return true;',
                    '}',
                    'return !(',
                    '    item?.sharingProperties ||',
                    '    item?.businessUnitAvailability ||',
                    "    item.r__folder_Path?.startsWith('Shared Content/')",
                    ');'
                ),
            }),

        onlyCBbyKey: () =>
            block('onlyCBbyKey', {
                failed: 'failedMsg: `Content blocks must be referenced by key. Replace ContentBlockById / ContentBlockByName (e.g. run mcdev rcb --bu ${bu} --to key).`,',
                passed: lines(
                    "if (definition.type !== 'asset' || !Array.isArray(codeExtractItemArr)) {",
                    '    return true;',
                    '}',
                    'for (const snippet of codeExtractItemArr) {',
                    '    const lowered = snippet.content.toLowerCase();',
                    "    if (lowered.includes('contentblockbyid') || lowered.includes('contentblockbyname')) {",
                    '        return false;',
                    '    }',
                    '}',
                    'return true;'
                ),
            }),

        noMultipartEmails: () =>
            block('noMultipartEmails', {
                failed: 'failedMsg: `isMultipart must be false for journey email activities; enabling it duplicates activities.`,',
                fix: lines(
                    'if (this.passed()) {',
                    '    return true;',
                    '}',
                    'for (const activity of item.activities || []) {',
                    "    if (activity.type === 'EMAILV2' && activity.configurationArguments) {",
                    '        activity.configurationArguments.isMultipart = false;',
                    '    }',
                    '}',
                    'return false;'
                ),
                passed: lines(
                    "if (definition.type !== 'journey') {",
                    '    return true;',
                    '}',
                    'for (const activity of item.activities || []) {',
                    "    if (activity.type === 'EMAILV2' && activity.configurationArguments?.isMultipart) {",
                    '        return false;',
                    '    }',
                    '}',
                    'return true;'
                ),
            }),

        payloadParameterDEsNoPrimaryKey: () =>
            blockRaw(
                'payloadParameterDEsNoPrimaryKey',
                lines(
                    '/** @type {string[]} */',
                    'offenders: [],',
                    'get failedMsg() {',
                    "    return `_PayloadParameters DEs may not have primary keys. Offending field(s): ${this.offenders.join(', ')}. Set IsPrimaryKey = false.`;",
                    '},',
                    '/** @type {validationRuleTest} */',
                    'passed: function () {',
                    "    if (definition.type !== 'dataExtension') {",
                    '        return true;',
                    '    }',
                    '    const isPayload =',
                    "        String(item?.Name).endsWith('_PayloadParameters') ||",
                    "        String(item?.CustomerKey).endsWith('_PayloadParameters');",
                    '    if (!isPayload) {',
                    '        return true;',
                    '    }',
                    '    this.offenders = (item.Fields || [])',
                    '        .filter((field) => field.IsPrimaryKey === true)',
                    '        .map((field) => field.Name);',
                    '    return this.offenders.length === 0;',
                    '},',
                    '/** @type {validationRuleFix} */',
                    'fix: function () {',
                    '    if (this.passed()) {',
                    '        return true;',
                    '    }',
                    '    for (const field of item.Fields || []) {',
                    '        if (field.IsPrimaryKey === true) {',
                    '            field.IsPrimaryKey = false;',
                    '        }',
                    '    }',
                    '    return false;',
                    '}'
                )
            ),

        noMidDependentCode: (state) => {
            const mids = (state.mids || []).map(String);
            return block('noMidDependentCode', {
                failed:
                    'failedMsg: `Found code that hard-codes a business-unit MID (' +
                    mids.join(', ') +
                    '). Use mcdev market variables instead.`,',
                passed: lines(
                    'const mids = ' + jsonLit(mids) + ';',
                    "if (definition.type !== 'asset' || !Array.isArray(codeExtractItemArr) || mids.length === 0) {",
                    '    return true;',
                    '}',
                    'for (const snippet of codeExtractItemArr) {',
                    '    const content = snippet.content;',
                    '    if (mids.some((mid) => content.includes(mid))) {',
                    '        return false;',
                    '    }',
                    '}',
                    'return true;'
                ),
            });
        },

        filterPrefixByBu: (state) =>
            blockRaw(
                'filterPrefixByBu',
                lines(
                    '/** @type {Object.<string, string[]>} BU -> forbidden prefixes */',
                    'blacklistByBu: ' + prettyInline(state.prefixBlacklist) + ',',
                    'get failedMsg() {',
                    '    const list = this.blacklistByBu[bu] || [];',
                    "    return `Prefix not allowed on this BU. Blacklisted prefixes: ${list.join(', ')}`;",
                    '},',
                    '/** @type {validationRuleFix} */',
                    'fix: function () {',
                    '    return this.passed() || null;',
                    '},',
                    '/** @type {validationRuleTest} */',
                    'passed: function () {',
                    '    const blacklist = this.blacklistByBu[bu] || [];',
                    '    if (blacklist.length === 0) {',
                    '        return true;',
                    '    }',
                    "    const key = '' + (item[definition.keyField] || '');",
                    "    const name = '' + (item[definition.nameField] || '');",
                    '    for (const prefix of blacklist) {',
                    '        if (key.startsWith(prefix) || name.startsWith(prefix)) {',
                    '            return false;',
                    '        }',
                    '    }',
                    '    return true;',
                    '}'
                )
            ),

        sendableDeRetention: (state) => {
            const r = state.retention || {};
            const type = r.c__retentionPolicy || 'individialRecords';
            const length = typeof r.DataRetentionPeriodLength === 'number' ? r.DataRetentionPeriodLength : 3;
            const unit = r.c__dataRetentionPeriodUnitOfMeasure || 'Months';
            const isReset = !!r.ResetRetentionPeriodOnImport;
            return blockRaw(
                'sendableDeRetention',
                lines(
                    'expected: {',
                    '    c__retentionPolicy: ' + jsonLit(type) + ',',
                    '    DataRetentionPeriodLength: ' + jsonLit(length) + ',',
                    '    c__dataRetentionPeriodUnitOfMeasure: ' + jsonLit(unit) + ',',
                    '    ResetRetentionPeriodOnImport: ' + jsonLit(isReset) + ',',
                    '},',
                    'get failedMsg() {',
                    "    return `Sendable DE retention policy is incorrect. Expected ${this.expected.DataRetentionPeriodLength} ${this.expected.c__dataRetentionPeriodUnitOfMeasure} for ${this.expected.c__retentionPolicy} with reset-on-import ${this.expected.ResetRetentionPeriodOnImport ? 'on' : 'off'}.`;",
                    '},',
                    '/** @type {validationRuleFix} */',
                    'fix: function () {',
                    '    if (this.passed()) {',
                    '        return true;',
                    '    }',
                    '    item.c__retentionPolicy = this.expected.c__retentionPolicy;',
                    '    item.DataRetentionPeriodLength = this.expected.DataRetentionPeriodLength;',
                    '    item.c__dataRetentionPeriodUnitOfMeasure = this.expected.c__dataRetentionPeriodUnitOfMeasure;',
                    '    item.ResetRetentionPeriodOnImport = this.expected.ResetRetentionPeriodOnImport;',
                    '    return false;',
                    '},',
                    '/** @type {validationRuleTest} */',
                    'passed: function () {',
                    "    if (!isProd || definition.type !== 'dataExtension' || !item.IsSendable) {",
                    '        return true;',
                    '    }',
                    '    return (',
                    '        item.c__retentionPolicy === this.expected.c__retentionPolicy &&',
                    '        item.DataRetentionPeriodLength === this.expected.DataRetentionPeriodLength &&',
                    '        item.c__dataRetentionPeriodUnitOfMeasure ===',
                    '            this.expected.c__dataRetentionPeriodUnitOfMeasure &&',
                    '        item.ResetRetentionPeriodOnImport === this.expected.ResetRetentionPeriodOnImport',
                    '    );',
                    '}'
                )
            );
        },
    };

    const FILTER_TEXT_BLACKLIST = [
        '/test',
        '-test',
        '_test',
        ' test',
        '/archive',
        '-archive',
        '_archive',
        ' archive',
    ];
    const FILTER_TEXT_WHITELIST = ['passed_test', 'test_invite'];

    /**
    Rules that require the module-scope prodBUorNotMap.
     */
    const PROD_SCOPED_RULES = new Set(['sendableDeRetention']);

    /**
     * Indent a multi-line body by a number of 4-space levels.
     *
     * @param {string} text raw body
     * @param {number} levels indent depth
     * @returns {string} indented text
     */
    function indent(text, levels) {
        const pad = ' '.repeat(4).repeat(levels);
        return text
            .split('\n')
            .map((line) => (line.length > 0 ? pad + line : line))
            .join('\n');
    }

    /**
     * Join body lines that live inside a `passed`/`fix` function (indented one level in).
     *
     * @param {...string} parts body lines
     * @returns {string} the joined + indented body
     */
    function lines(...parts) {
        return parts.join('\n');
    }

    /**
     * Emit a standard rule object with `failedMsg`, optional `fix`, and `passed`.
     *
     * @param {string} name rule key
     * @param {{failed: string, fix?: string, passed: string}} parts rule pieces
     * @returns {string} rule literal source (indented for the returned map)
     */
    function block(name, parts) {
        let body = '';
        body += indent(parts.failed, 3) + '\n';
        if (parts.fix) {
            body += indent('/** @type {validationRuleFix} */', 3) + '\n';
            body += indent('fix: function () {', 3) + '\n';
            body += indent(parts.fix, 4) + '\n';
            body += indent('},', 3) + '\n';
        }
        body += indent('/** @type {validationRuleTest} */', 3) + '\n';
        body += indent('passed: function () {', 3) + '\n';
        body += indent(parts.passed, 4) + '\n';
        body += indent('},', 3) + '\n';
        return indent(jsonLit(name) + ': {', 2) + '\n' + body + indent('},', 2) + '\n';
    }

    /**
     * Emit a rule whose body is fully hand-authored (for getters / extra properties).
     *
     * @param {string} name rule key
     * @param {string} rawBody complete inner body (without the wrapping braces)
     * @returns {string} rule literal source
     */
    function blockRaw(name, rawBody) {
        return (
            indent(jsonLit(name) + ': {', 2) +
            '\n' +
            indent(rawBody, 3) +
            '\n' +
            indent('},', 2) +
            '\n'
        );
    }

    /**
     * Standard "skip the item to fix" body.
     *
     * @returns {string} fix body
     */
    function skipFix() {
        return 'return this.passed() || null;';
    }

    /**
     * Render a BU -> string[] map as an indented inline object literal.
     *
     * @param {{[key: string]: string[]}} map source map
     * @returns {string} object literal
     */
    function prettyInline(map) {
        const keys = Object.keys(map || {});
        if (keys.length === 0) {
            return '{}';
        }
        const inner = keys.map((k) => ' '.repeat(16) + jsonLit(k) + ': ' + jsonLit(map[k]) + ',').join('\n');
        return '{\n' + inner + '\n            }';
    }

    /**
     * Build the complete `.mcdev-validations.js` source text.
     *
     * @param {ValidationsState} wizardState collected answers
     * @returns {string} file source
     */
    function buildValidations(wizardState) {
        const state = wizardState || {};
        const selected = Array.isArray(state.selectedRules) ? [...state.selectedRules] : [];
        // keySuffix is always emitted first.
        const ordered = ['keySuffix', ...selected.filter((id) => id !== 'keySuffix')];
        const isNeedProductionMap = ordered.some((id) => PROD_SCOPED_RULES.has(id));

        let out = header(state, isNeedProductionMap);
        out += functionOpen(isNeedProductionMap);

        for (const id of ordered) {
            const emit = RULES[id];
            if (emit) {
                out += emit(state);
            }
        }

        out += '    };\n}\n';
        return out;
    }

    const api = { buildValidations: buildValidations };

    // Browser global.
    global.mpbValidationsBuilder = api;

    // UMD-style footer for the Node test.
    if (typeof module !== 'undefined' && module.exports) {
        module.exports = api;
    }
})(typeof globalThis === 'undefined' ? new Function('return this')() : globalThis);
